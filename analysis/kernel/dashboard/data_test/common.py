def sniff_delimiter(path: str | Path) -> str:
    """Return '|' for sqlite3 default output, ',' for CSV."""
    with open(path, newline="", encoding="utf-8", errors="ignore") as fh:
        first = fh.readline()
    return "|" if first.count("|") > first.count(",") else ","


def clean(value: str | None) -> str:
    """Strip whitespace and the quoting bqrs/sqlite add."""
    return (value or "").strip().strip('"').strip("'")


KERNEL_TOP_DIRS = {
    "arch",
    "block",
    "certs",
    "crypto",
    "drivers",
    "fs",
    "include",
    "init",
    "io_uring",
    "ipc",
    "kernel",
    "lib",
    "mm",
    "net",
    "rust",
    "samples",
    "scripts",
    "security",
    "sound",
    "tools",
    "usr",
    "virt",
}


def load_rows(path: str | Path, columns: list[str]) -> list[dict]:
    """Load a CSV into dicts keyed by `columns` (positional binding).

    Automatically skips a leading header row if present. Short rows are skipped.
    """
    delim = sniff_delimiter(path)
    rows: list[dict] = []
    with open(path, newline="", encoding="utf-8", errors="ignore") as fh:
        for idx, raw in enumerate(csv.reader(fh, delimiter=delim)):
            if len(raw) < len(columns):
                continue
            cleaned_first = clean(raw[0])
            # Skip CSV header row generated by `codeql bqrs decode` or sqlite
            if idx == 0 and (
                cleaned_first == columns[0]
                or cleaned_first
                in (
                    "col0",
                    "cdc",
                    "call_value",
                    "call_site",
                    "syscall",
                    "function_name",
                    "definition",
                    "struct_name",
                    "func",
                    "config",
                    "name",
                    "type",
                    "conditions",
                    "macro_name",
                    "macroinvocation_name",
                )
            ):
                continue
            rows.append({c: clean(v) for c, v in zip(columns, raw)})
    return rows


def canonical_path(path_str: str) -> str:
    """Reduce a build-specific absolute path to a kernel-relative one."""
    path_str = clean(path_str)
    parts = [pt for pt in path_str.split("/") if pt]
    if (
        parts
        and parts[0] in KERNEL_TOP_DIRS
        and not path_str.startswith("/usr/local")
        and not path_str.startswith("/usr/src")
    ):
        return "/".join(parts)
    for marker in ("linux_v", "linux-"):
        if marker in path_str:
            after = path_str.split(marker, 1)[1]
            if "/" in after:
                return after.split("/", 1)[1].lstrip("/")
    for i, part in enumerate(parts):
        if (
            i == 0
            and part == "usr"
            and len(parts) > 1
            and parts[1] in ("local", "src", "share", "home")
        ):
            continue
        if part in KERNEL_TOP_DIRS and i < len(parts) - 1:
            return "/".join(parts[i:])
    return path_str.lstrip("/")


def is_int(value: str) -> bool:
    """Return True if `value` can be parsed as an integer."""
    try:
        int(value)
        return True
    except (TypeError, ValueError):
        return False


def locate_kernel_source_file(raw_file: str, kernel: str) -> str | None:
    """Resolve `raw_file` to an on-disk kernel source file if available."""
    if not raw_file:
        return None
    stripped = raw_file.removeprefix("file://")
    if Path(stripped).is_file():
        return stripped
    clean_rel = canonical_path(raw_file)
    if Path(clean_rel).is_file():
        return clean_rel

    workspace = Path(
        os.environ.get(
            "WORKSPACE_DIR",
            str(Path("~/kernel_codeql_workspace").expanduser()),
        )
    )
    candidates = []
    if kernel and kernel != "unknown":
        clean_ver = kernel.lstrip("v")
        candidates.append(workspace / f"linux_v{clean_ver}")
    if workspace.is_dir():
        for entry in sorted(workspace.iterdir()):
            if entry.name.startswith("linux_v"):
                candidates.append(entry)

    for repo_dir in candidates:
        candidate = repo_dir / clean_rel
        if candidate.is_file():
            return str(candidate)
    return None


def scan_compiled_c_targets(
    function_locations: list[dict],
    kernel: str,
    patterns: dict[str, str | tuple[str, str] | object],
    path_filter: dict[str, str] | None = None,
) -> dict[str, set[str]]:
    """Scan on-disk compiled .c files for C callback/registration patterns.

    Only scans `.c` files present in `function_locations` (i.e. actually
    compiled by the active `.config`), and only retains captured identifiers
    that exist in `function_locations`. A pattern value may be a regex string,
    a compiled `re.Pattern`, or a `(block_regex, item_regex)` tuple (where
    `block_regex` matches an enclosing C declaration with `re.DOTALL` and
    `item_regex` extracts identifiers inside each matched block).
    """
    import re

    known_funcs = {r["function_name"] for r in function_locations}
    compiled_c_files = sorted(
        {
            r["file_path"]
            for r in function_locations
            if r.get("file_path", "").endswith(".c")
        }
    )
    if not compiled_c_files:
        return {}

    probe = locate_kernel_source_file(compiled_c_files[0], kernel)
    if not probe:
        return {}

    compiled_res: dict[str, object] = {}
    for k, pat in patterns.items():
        if isinstance(pat, tuple):
            compiled_res[k] = (
                re.compile(pat[0], re.DOTALL),
                re.compile(pat[1]),
            )
        elif isinstance(pat, str):
            compiled_res[k] = re.compile(pat)
        else:
            compiled_res[k] = pat

    results: dict[str, set[str]] = {k: set() for k in patterns}

    for raw_path in compiled_c_files:
        src_path = locate_kernel_source_file(raw_path, kernel)
        if not src_path:
            continue
        rel = canonical_path(raw_path)
        try:
            with open(src_path, encoding="utf-8", errors="ignore") as fh:
                text = fh.read()
        except OSError:
            continue
        for key, rx in compiled_res.items():
            req_sub = (path_filter or {}).get(key)
            if req_sub and not rel.startswith(req_sub):
                continue
            if isinstance(rx, tuple):
                block_rx, item_rx = rx
                for block_match in block_rx.finditer(text):
                    for match in item_rx.finditer(block_match.group(0)):
                        fn = match.group(1)
                        if fn in known_funcs:
                            results[key].add(fn)
            else:
                for match in rx.finditer(text):
                    fn = match.group(1)
                    if fn in known_funcs:
                        results[key].add(fn)
    return results



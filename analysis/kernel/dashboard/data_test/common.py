# baselines: recorded stats from a validated run, for drift detection
# --------------------------------------------------------------------------- #


def load_baseline(path: str | Path | None, table: str) -> dict:
    """Load baseline dictionary for `table` from JSON file at `path`."""
    if not path or not Path(path).exists():
        return {}
    with open(path, encoding="utf-8") as fh:
        return json.load(fh).get(table, {})


def drift(
    observed: float, expected: float, tolerance: float
) -> tuple[bool, str]:
    """Return whether |observed-expected| is within `tolerance`."""
    if expected is None:
        return True, "no baseline"
    delta = abs(observed - expected)
    ok = delta <= tolerance
    msg = (
        f"observed={observed:.3f} baseline={expected:.3f} "
        f"delta={delta:.3f} tol={tolerance}"
    )
    return ok, msg


def top_counts(rows: list[dict], col: str, count: int = 8) -> list[tuple]:
    """Return the `count` most common values of `col` across `rows`."""
    return Counter(r[col] for r in rows).most_common(count)


def group_sets(
    rows: list[dict], key_col: str, value_col: str
) -> dict[str, set]:
    """Group `rows[value_col]` into sets keyed by `rows[key_col]`."""
    out: dict[str, set] = defaultdict(set)
    for row in rows:
        out[row[key_col]].add(row[value_col])
    return dict(out)

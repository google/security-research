# reporting: measurements must be visible even when checks pass
# --------------------------------------------------------------------------- #


def report(title: str, lines: dict | list[tuple] | None = None) -> None:
    """Print a measurement block to stderr so it survives pytest capture."""
    print(f"\n--- {title} ---", file=sys.stderr)
    if isinstance(lines, dict):
        lines = list(lines.items())
    for item in lines or []:
        if isinstance(item, (tuple, list)) and len(item) >= 2:
            key = str(item[0])
            value = "  ".join(str(x) for x in item[1:])
        else:
            key, value = str(item), ""
        print(f"    {key:<44} {value}", file=sys.stderr)


def pct(numerator: int, denominator: int) -> float:
    """Compute percentage `100.0 * numerator / denominator` safely."""
    return 100.0 * numerator / denominator if denominator else 0.0



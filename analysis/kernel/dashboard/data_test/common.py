def agreement(
    rows: list[dict],
    key_col: str,
    value_col: str,
    reference: dict[str, str],
) -> tuple[int, int, list[tuple]]:
    """Compare rows[value_col] against a reference map keyed on rows[key_col].

    Returns (checked, matched, sample_mismatches).
    """
    checked = matched = 0
    mismatches: list[tuple] = []
    for row in rows:
        key = row[key_col]
        if key not in reference:
            continue
        checked += 1
        if row[value_col] == reference[key]:
            matched += 1
        elif len(mismatches) < 15:
            mismatches.append((key, row[value_col], reference[key]))
    return checked, matched, mismatches


